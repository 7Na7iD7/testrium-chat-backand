-- تا الان appeals_insert_own (migration 0006) فقط مالکیت ردیف را چک
-- می‌کرد (student_code = خود دانشجو)، بدون هیچ محدودیت زمانی. کلاینت
-- (exam_result_screen.dart) بعداً یک قانون UI اضافه کرد: دانشجو فقط
-- تا ۴۸ ساعت پس از پایان آزمون (exams.available_until) اجازه‌ی ثبت
-- اعتراض جدید دارد. اما طبق همان اصل معماری‌ای که در کل این پروژه
-- رعایت شده (RLS مسئول واقعی کنترل دسترسی است، نه صرفاً UI)، این قانون
-- باید مستقل از کلاینت هم اجرا شود؛ وگرنه یک کاربر با درخواست مستقیم
-- به Supabase (بدون عبور از اپ) می‌تواند این مهلت را دور بزند.
--
-- توجه: عمداً هیچ مهلت مشابهی برای پاسخ استاد (appeals_update_professor_own_section)
-- اضافه نمی‌شود. قفل‌کردن پاسخ استاد بعد از یک مدت مشخص باعث می‌شود
-- اعتراض دانشجو برای همیشه در وضعیت pending گیر بماند و هیچ راهی برای
-- حل آن نباشد — که آسیبش از تاخیر بیشتر است. رویکرد درست برای این
-- سمت، فقط یادآوری/تشدید (که در لایه‌ی اعلان اپ پیاده شده) است، نه
-- مسدودسازی سخت.
-- ====================================================================

drop policy if exists "appeals_insert_own" on public.exam_appeals;

create policy "appeals_insert_own"
  on public.exam_appeals for insert
  with check (
    student_code = public.current_student_code()
    and exists (
      select 1 from public.exams e
      where e.exam_id = exam_id
        and now() <= e.available_until + interval '48 hours'
    )
  );

