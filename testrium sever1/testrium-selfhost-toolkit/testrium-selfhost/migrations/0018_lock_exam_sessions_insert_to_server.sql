-- مشکل: تا الان submit نتیجه‌ی آزمون از اپ به‌صورت upsert مستقیم
-- کلاینت روی exam_sessions انجام می‌شد. سیاست exam_sessions_insert_own
-- (migration 0001) فقط مالکیت ردیف (student_code = خود دانشجو) را
-- چک می‌کرد، نه صحت خودِ نمره. یعنی هر دانشجویی که یک درخواست دستی
-- (بدون عبور از اپ) با همان نشست خودش به Supabase می‌زد، می‌توانست
-- earned_score و mcq_correct_count دلخواه برای «اولین» ثبت آزمونش
-- بفرستد و بدون هیچ تصحیح واقعی، نمره‌ی خودش را جعل کند.
--
-- راه‌حل معماری (سمت کد اپ، هم‌زمان با این migration): submit نتیجه
-- دیگر هیچ‌وقت مستقیم upsert نمی‌زند؛ همیشه از طریق Edge Function
-- submit-exam-result (service_role، هویت از JWT، تصحیح MCQ سمت سرور
-- از روی فایل واقعیِ سوالات) انجام می‌شود. در نتیجه دانشجو دیگر هیچ
-- نیاز مشروعی به INSERT مستقیم روی exam_sessions ندارد — این migration
-- همان policy را حذف می‌کند تا مسیر دورزدن هم در سطح دیتابیس (نه فقط
-- در کد اپ) بسته باشد.
--
-- توجه: exam_sessions_update_own (migration 0011) دست‌نخورده می‌ماند؛
-- چون دیگر هیچ ردیفی قبل از submit توسط کلاینت insert نمی‌شود، عملاً
-- دیگر چیزی برای دانشجو برای update باقی نمی‌ماند (بی‌ضرر، برای
-- سازگاری با هر مسیر legacy احتمالی نگه داشته شده، نه یک حفره‌ی جدید).
-- ====================================================================

drop policy if exists "exam_sessions_insert_own" on public.exam_sessions;

