-- ====================================================================
-- Testrium — Migration 0027: نقش‌های ادمین (Role-Based Access)
-- ====================================================================
-- روی جدول admins (که در 0026 ساخته شد) یک ستون role اضافه می‌کند.
-- سه مقدار مجاز: full (دسترسی کامل)، students (فقط ثبت‌نام/دانشجو)،
-- professors (فقط مدیریت استاد). پیش‌فرض 'full' است تا ادمین‌های
-- موجود (بوت‌استرپ‌شده قبل از این migration) بدون تغییر دستی همچنان
-- دسترسی کامل داشته باشند.
--
-- این محدودیت فقط یک ستون دیتابیسی نیست — خودِ Edge Function
-- admin-academic-ops پیش از اجرای هر اکشن، این مقدار را در برابر یک
-- نگاشت اکشن-به-نقش بررسی می‌کند (نگاه کن به ACTION_ROLES در همان
-- فایل) و در صورت عدم تطابق با کد ۴۰۳ رد می‌کند.
-- ====================================================================

alter table admins
    add column if not exists role text not null default 'full'
    check (role in ('full', 'students', 'professors'));

update admins set role = 'full' where role is null;